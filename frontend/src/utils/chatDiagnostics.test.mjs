import assert from 'node:assert/strict';
import { createChatDiagnostics } from './chatDiagnostics.js';
let time = 0, id = 0, enabled = true;
const reports = [];
const diagnostics = createChatDiagnostics({ enabled: () => enabled, now: () => time, makeId: () => `${++id}`, report: (sample) => reports.push(sample) });
const request = diagnostics.start('dm.send');
time = 120;
diagnostics.finish({ clientMessageId: request, content: 'must not appear in diagnostics' }, { 'x-chat-server-ms': '35' });
assert.deepEqual(reports, [{ event: 'dm.send', echoRoundTripMs: 120, serverMs: 35, residualRoundTripMs: 85 }]);
diagnostics.finish({ clientMessageId: request });
assert.equal(reports.length, 1, 'Duplicate echoes are recorded once');
const expired = diagnostics.start('dm.send');
time += 60001;
diagnostics.finish({ clientMessageId: expired });
assert.equal(reports.length, 1, 'Expired samples cannot grow or report indefinitely');
const cleared = diagnostics.start('channel.send');
diagnostics.clear();
diagnostics.finish({ clientMessageId: cleared });
assert.equal(reports.length, 1);
enabled = false;
assert.equal(diagnostics.start('dm.send'), undefined);
